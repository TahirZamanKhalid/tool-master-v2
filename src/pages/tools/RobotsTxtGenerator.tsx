import { useState } from "react";
import { ToolLayout } from "@/components/ToolLayout";
import { Card, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Checkbox } from "@/components/ui/checkbox";
import { toast } from "sonner";
import { FileText, Copy, Download } from "lucide-react";

const RobotsTxtGenerator = () => {
  const [sitemap, setSitemap] = useState("");
  const [crawlDelay, setCrawlDelay] = useState("");
  const [disallowPaths, setDisallowPaths] = useState("/admin\n/private\n/wp-admin");
  const [allowAllBots, setAllowAllBots] = useState(true);
  const [specificBots, setSpecificBots] = useState("");
  const [generatedRobots, setGeneratedRobots] = useState("");

  const generateRobotsTxt = () => {
    let content = "# robots.txt generated by ToolMaster Pro\n";
    content += "# " + new Date().toLocaleDateString() + "\n\n";

    if (allowAllBots) {
      content += "User-agent: *\n";

      // Add disallow paths
      if (disallowPaths.trim()) {
        const paths = disallowPaths.split("\n").filter(p => p.trim());
        paths.forEach(path => {
          content += `Disallow: ${path.trim()}\n`;
        });
      } else {
        content += "Allow: /\n";
      }

      // Add crawl delay if specified
      if (crawlDelay && parseInt(crawlDelay) > 0) {
        content += `Crawl-delay: ${crawlDelay}\n`;
      }

      content += "\n";
    }

    // Add specific bot rules
    if (specificBots.trim()) {
      const botRules = specificBots.split("\n").filter(b => b.trim());
      botRules.forEach(rule => {
        content += rule.trim() + "\n";
      });
      content += "\n";
    }

    // Add sitemap
    if (sitemap.trim()) {
      const sitemaps = sitemap.split("\n").filter(s => s.trim());
      sitemaps.forEach(sm => {
        const url = sm.trim();
        if (url.startsWith("http")) {
          content += `Sitemap: ${url}\n`;
        } else {
          content += `Sitemap: https://${url}\n`;
        }
      });
    }

    setGeneratedRobots(content);
    toast.success("robots.txt generated successfully!");
  };

  const copyRobots = () => {
    navigator.clipboard.writeText(generatedRobots);
    toast.success("Copied to clipboard!");
  };

  const downloadRobots = () => {
    const blob = new Blob([generatedRobots], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "robots.txt";
    a.click();
    toast.success("robots.txt downloaded!");
  };

  const loadTemplate = (template: string) => {
    switch (template) {
      case "allow-all":
        setDisallowPaths("");
        setAllowAllBots(true);
        break;
      case "block-all":
        setDisallowPaths("/");
        setAllowAllBots(true);
        break;
      case "wordpress":
        setDisallowPaths("/wp-admin/\n/wp-includes/\n/wp-content/plugins/\n/wp-content/themes/");
        setAllowAllBots(true);
        break;
      case "ecommerce":
        setDisallowPaths("/cart\n/checkout\n/account\n/admin\n/search");
        setAllowAllBots(true);
        break;
    }
    toast.success(`${template} template loaded!`);
  };

  return (
    <ToolLayout
      title="Robots.txt Generator"
      description="Generate robots.txt file for your website to control search engine crawlers. Free robots.txt builder for SEO."
      category="SEO & Marketing"
      instructions={[
        "Enter your sitemap URL(s)",
        "Specify paths to disallow crawlers",
        "Set crawl delay if needed (in seconds)",
        "Add specific bot rules (optional)",
        "Generate and download robots.txt file"
      ]}
      relatedTools={[
        { name: "XML Sitemap Generator", path: "/tools/xml-sitemap-generator" },
        { name: "Meta Tag Generator", path: "/tools/meta-tag-generator" },
        { name: "Sitemap Validator", path: "/tools/sitemap-validator" }
      ]}
    >
      <div className="grid gap-6">
        <Card>
          <CardContent className="p-6 space-y-6">
            <div>
              <div className="flex items-center justify-between mb-2">
                <Label>Quick Templates</Label>
              </div>
              <div className="grid grid-cols-2 md:grid-cols-4 gap-2">
                <Button onClick={() => loadTemplate("allow-all")} variant="outline" size="sm">
                  Allow All
                </Button>
                <Button onClick={() => loadTemplate("block-all")} variant="outline" size="sm">
                  Block All
                </Button>
                <Button onClick={() => loadTemplate("wordpress")} variant="outline" size="sm">
                  WordPress
                </Button>
                <Button onClick={() => loadTemplate("ecommerce")} variant="outline" size="sm">
                  E-commerce
                </Button>
              </div>
            </div>

            <div>
              <Label htmlFor="sitemap">Sitemap URL(s) (one per line)</Label>
              <Textarea
                id="sitemap"
                value={sitemap}
                onChange={(e) => setSitemap(e.target.value)}
                placeholder="https://example.com/sitemap.xml&#10;https://example.com/sitemap-posts.xml"
                className="mt-2 h-20"
              />
            </div>

            <div className="flex items-center space-x-2">
              <Checkbox
                id="allow-all-bots"
                checked={allowAllBots}
                onCheckedChange={(checked) => setAllowAllBots(checked as boolean)}
              />
              <Label htmlFor="allow-all-bots" className="cursor-pointer">
                Apply rules to all bots (User-agent: *)
              </Label>
            </div>

            <div>
              <Label htmlFor="disallow-paths">Disallow Paths (one per line)</Label>
              <Textarea
                id="disallow-paths"
                value={disallowPaths}
                onChange={(e) => setDisallowPaths(e.target.value)}
                placeholder="/admin&#10;/private&#10;/wp-admin"
                className="mt-2 h-24"
              />
              <p className="text-xs text-muted-foreground mt-1">
                Leave empty to allow all paths
              </p>
            </div>

            <div>
              <Label htmlFor="crawl-delay">Crawl Delay (seconds)</Label>
              <Input
                id="crawl-delay"
                type="number"
                value={crawlDelay}
                onChange={(e) => setCrawlDelay(e.target.value)}
                placeholder="10"
                className="mt-2"
              />
              <p className="text-xs text-muted-foreground mt-1">
                Optional: Delay between successive requests (in seconds)
              </p>
            </div>

            <div>
              <Label htmlFor="specific-bots">Specific Bot Rules (optional)</Label>
              <Textarea
                id="specific-bots"
                value={specificBots}
                onChange={(e) => setSpecificBots(e.target.value)}
                placeholder="User-agent: Googlebot&#10;Disallow: /private/"
                className="mt-2 h-20"
              />
            </div>

            <Button onClick={generateRobotsTxt} className="w-full" size="lg">
              <FileText className="h-4 w-4 mr-2" />
              Generate robots.txt
            </Button>
          </CardContent>
        </Card>

        {generatedRobots && (
          <Card className="border-primary/20">
            <CardContent className="p-6 space-y-4">
              <div className="flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <FileText className="h-5 w-5 text-primary" />
                  <h3 className="text-lg font-semibold">Generated robots.txt</h3>
                </div>
                <div className="flex gap-2">
                  <Button onClick={copyRobots} size="sm" variant="outline">
                    <Copy className="h-4 w-4 mr-2" />
                    Copy
                  </Button>
                  <Button onClick={downloadRobots} size="sm">
                    <Download className="h-4 w-4 mr-2" />
                    Download
                  </Button>
                </div>
              </div>

              <pre className="p-4 bg-muted rounded-lg text-sm overflow-x-auto">
                {generatedRobots}
              </pre>
            </CardContent>
          </Card>
        )}

        <Card>
          <CardContent className="p-6">
            <h3 className="text-lg font-semibold mb-4">robots.txt Best Practices</h3>
            <ul className="space-y-2 text-sm text-muted-foreground">
              <li className="flex items-start gap-2">
                <span className="text-primary">✓</span>
                <span><strong>Location:</strong> Place robots.txt in your website root directory</span>
              </li>
              <li className="flex items-start gap-2">
                <span className="text-primary">✓</span>
                <span><strong>Test it:</strong> Use Google Search Console to test your robots.txt</span>
              </li>
              <li className="flex items-start gap-2">
                <span className="text-primary">✓</span>
                <span><strong>Don't hide sensitive data:</strong> robots.txt is publicly accessible</span>
              </li>
              <li className="flex items-start gap-2">
                <span className="text-primary">✓</span>
                <span><strong>Sitemap:</strong> Always include your sitemap URL(s)</span>
              </li>
              <li className="flex items-start gap-2">
                <span className="text-primary">✓</span>
                <span><strong>Wildcards:</strong> Use * for pattern matching (e.g., /private*)</span>
              </li>
              <li className="flex items-start gap-2">
                <span className="text-primary">✓</span>
                <span><strong>Case-sensitive:</strong> Paths in robots.txt are case-sensitive</span>
              </li>
            </ul>
          </CardContent>
        </Card>
      </div>
    </ToolLayout>
  );
};

export default RobotsTxtGenerator;
